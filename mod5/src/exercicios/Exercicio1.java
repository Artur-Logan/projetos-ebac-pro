package exercicios;

/*
Essa classe tem como objetivo fazer as principais operações de uma calculadora
 */
public class Exercicio1 {
/*
Somar recebe 2 inteiros, retornando  a soma deles;
 */
    public int somar(int a, int b){
        return a + b;
    }
    /*
    Subtrair recebe 2 inteiros, retornando a subtração deles;
    */
    public int subtrair(int a, int b){
        return a - b;
    }
    /*
    Multiplicar recebe 2 inteiros, retornando o porduto deles;
    */
    public int multiplicar(int a, int b){
        return a * b;
    }
    /*
    Dividir recebe 2 inteiros, retornando a divisão deles;
    */
    public int dividir(int a, int b) {
        return a / b;
    }
}
